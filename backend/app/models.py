"""Database tables, as SQLAlchemy ORM models.

The schema itself is created by the Alembic migrations in migrations/versions.
These classes describe the same tables for the application code, and
tests/integration/test_schema.py checks that the two never drift apart.
"""

import enum
from datetime import datetime
from typing import Any

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Identity,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import ARRAY, JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.db import Base

# Output size of nomic-embed-text, confirmed by scripts/check_embedding_dim.py.
# Changing the embedding model means changing this number, adding a migration
# and re-embedding every chunk: vectors from different models can't be mixed.
EMBEDDING_DIM = 768


class DocumentStatus(enum.StrEnum):
    PROCESSING = "processing"
    READY = "ready"
    FAILED = "failed"


class User(Base):
    __tablename__ = "users"
    __table_args__ = (
        # The app lowercases emails before saving. This constraint guarantees
        # it, so "Alice@x.com" and "alice@x.com" can never be two accounts.
        CheckConstraint("email = lower(email)", name="email_lowercase"),
    )

    # BIGINT identity columns: the SQL-standard replacement for SERIAL.
    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    email: Mapped[str] = mapped_column(String(320), unique=True)
    password_hash: Mapped[str] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())


class Document(Base):
    __tablename__ = "documents"
    __table_args__ = (
        # A CHECK constraint instead of a Postgres ENUM type: adding a status
        # later is a one-line migration, while altering an ENUM is awkward.
        CheckConstraint("status IN ('processing', 'ready', 'failed')", name="status_valid"),
        CheckConstraint("page_count IS NULL OR page_count > 0", name="page_count_positive"),
        CheckConstraint(
            "summary_provider IS NULL OR summary_provider IN "
            "('anthropic', 'ollama_gpu', 'ollama', 'mock')",
            name="summary_provider_valid",
        ),
        # Serves "list my documents, newest first". Because user_id is the
        # leading column, it also serves any lookup by user_id alone.
        Index("ix_documents_user_id_created_at", "user_id", "created_at"),
    )

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    user_id: Mapped[int] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"))
    # Shown to the user only. Never used to build a file path.
    original_filename: Mapped[str] = mapped_column(String(255))
    # Random name generated by the server; this is the name on disk.
    stored_filename: Mapped[str] = mapped_column(String(64), unique=True)
    page_count: Mapped[int | None] = mapped_column(Integer)
    status: Mapped[str] = mapped_column(String(16), server_default=DocumentStatus.PROCESSING.value)
    # Short, user-safe reason when status is "failed" (never a stack trace).
    error_message: Mapped[str | None] = mapped_column(String(500))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    # Study summary (see app/rag/summary.py), written the first time it's
    # requested. NULL until then.
    summary: Mapped[dict[str, Any] | None] = mapped_column(JSONB)
    summary_provider: Mapped[str | None] = mapped_column(String(16))
    # The settings it was written with ({"tone", "length", "include_charts"}),
    # so the UI can offer to regenerate it when the user's settings change.
    summary_options: Mapped[dict[str, Any] | None] = mapped_column(JSONB)
    summary_created_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class Chunk(Base):
    __tablename__ = "chunks"
    __table_args__ = (
        # Postgres implements this constraint as a B-tree index on
        # (document_id, chunk_index). Because document_id is the leading
        # column, that same index answers "all chunks of document X" and
        # makes ON DELETE CASCADE fast, so a separate index on document_id
        # alone would only cost extra disk space and slower inserts.
        UniqueConstraint("document_id", "chunk_index"),
        CheckConstraint("chunk_index >= 0", name="chunk_index_non_negative"),
        CheckConstraint("page_start >= 1 AND page_end >= page_start", name="page_range_valid"),
        # Approximate nearest-neighbour index for similarity search.
        # HNSW rather than IVFFlat: IVFFlat clusters the vectors when the
        # index is built, so it needs representative data first and loses
        # recall as new documents arrive. HNSW needs no training step, works
        # on an empty table and gives better speed/recall, at the cost of
        # slower builds and more memory. vector_cosine_ops matches the
        # cosine distance operator (<=>) used by retrieval; an index only
        # helps queries that use its operator.
        Index(
            "ix_chunks_embedding_hnsw",
            "embedding",
            postgresql_using="hnsw",
            postgresql_ops={"embedding": "vector_cosine_ops"},
        ),
    )

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    document_id: Mapped[int] = mapped_column(ForeignKey("documents.id", ondelete="CASCADE"))
    chunk_index: Mapped[int] = mapped_column(Integer)
    page_start: Mapped[int] = mapped_column(Integer)
    page_end: Mapped[int] = mapped_column(Integer)
    text: Mapped[str] = mapped_column(Text)
    embedding: Mapped[list[float]] = mapped_column(Vector(EMBEDDING_DIM))


class QueryLog(Base):
    """Audit record of one question asked through the ask endpoint."""

    __tablename__ = "queries"
    __table_args__ = (
        CheckConstraint(
            "provider IS NULL OR provider IN ('anthropic', 'ollama_gpu', 'ollama', 'mock')",
            name="provider_valid",
        ),
        CheckConstraint("latency_ms >= 0", name="latency_ms_non_negative"),
        Index("ix_queries_user_id_created_at", "user_id", "created_at"),
        # Postgres doesn't index foreign keys automatically. Without this,
        # deleting a document would scan the whole queries table to find
        # the rows to update.
        Index("ix_queries_document_id", "document_id"),
    )

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    user_id: Mapped[int] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"))
    # SET NULL rather than CASCADE: the audit trail of who asked what
    # survives even if the document is later deleted.
    document_id: Mapped[int | None] = mapped_column(ForeignKey("documents.id", ondelete="SET NULL"))
    question: Mapped[str] = mapped_column(Text)
    # NULL when answering failed; the attempt is still recorded.
    answer: Mapped[str | None] = mapped_column(Text)
    # The provider that actually produced the answer (after any fallback).
    provider: Mapped[str | None] = mapped_column(String(16))
    # A plain array, not a foreign key: it's a snapshot of what retrieval
    # returned at the time, kept even if those chunks are deleted later.
    retrieved_chunk_ids: Mapped[list[int]] = mapped_column(ARRAY(BigInteger), server_default="{}")
    latency_ms: Mapped[int] = mapped_column(Integer)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
